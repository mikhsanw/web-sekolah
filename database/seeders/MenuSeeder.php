    private function storeMenu(array $item, ?string $parentId = null): void
    {
        $children = $item['children'] ?? [];
        unset($item['children']);

        $menu = Menu::updateOrCreate(
            ['code' => $item['code']],
            array_merge($item, ['parent_id' => $parentId])
        );

        foreach ($children as $child) {
            $this->storeMenu($child, $menu->id);
        }
    }
